#!/usr/bin/env python3
"""Generate the lossless RLE backplanes for one video backend."""

import argparse
from itertools import groupby
from pathlib import Path

HEIGHT = 240
COLORS = 32
PALETTE_BYTES = COLORS * 3
WIDTHS = (320, 384)
HEADER = b"GBBP\x01"


def read_skin(path, width):
    data = path.read_bytes()
    expected = len(HEADER) + sum(PALETTE_BYTES + 2 * w * HEIGHT for w in WIDTHS)
    if len(data) != expected or not data.startswith(HEADER):
        raise ValueError(f"{path}: invalid GBBP v1 file")
    offset = len(HEADER)
    if width == 384:
        offset += PALETTE_BYTES + 2 * 320 * HEIGHT
    palette = data[offset:offset + PALETTE_BYTES]
    offset += PALETTE_BYTES
    size = width * HEIGHT
    cells = data[offset:offset + 2 * size]
    if max(cells) >= COLORS:
        raise ValueError(f"{path}: color index outside the 32-color palette")
    return palette, (cells[:size], cells[size:])


def encode(cells):
    output = bytearray()
    for color, group in groupby(cells):
        run = sum(1 for _ in group)
        slot = 192 + color + (16 if color >= 8 else 0)
        whole, tail = divmod(run, 255)
        output.extend(bytes((255, slot)) * whole)
        if tail:
            output.extend((tail, slot))
    return output


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("width", type=int, choices=WIDTHS)
    parser.add_argument("output", type=Path)
    parser.add_argument("skins", type=Path, nargs=4)
    args = parser.parse_args()

    lines = ["/* Generated by embed_gbbp.py. */"]
    palettes = []
    for i, path in enumerate(args.skins):
        palette, scales = read_skin(path, args.width)
        palettes.append(palette)
        for scale, cells in enumerate(scales, start=2):
            encoded = encode(cells)
            lines.append(f"static const uint8_t skin_{i}_{scale}x[] = {{")
            for j in range(0, len(encoded), 20):
                lines.append("    " + ", ".join(map(str, encoded[j:j + 20])) + ",")
            lines.append("};")

    lines.append("static const struct builtin_backplane backplane_skins[] = {")
    for i, palette in enumerate(palettes):
        lines.append("    { {")
        for j in range(0, PALETTE_BYTES, 24):
            colors = [palette[k:k + 3].hex() for k in range(j, j + 24, 3)]
            lines.append("        " + ", ".join("0x" + c for c in colors) + ",")
        lines.append(f"    }}, {{ {{skin_{i}_2x, sizeof skin_{i}_2x}}, "
                     f"{{skin_{i}_3x, sizeof skin_{i}_3x}} }} }},")
    lines.append("};")
    args.output.write_text("\n".join(lines) + "\n", encoding="ascii")


if __name__ == "__main__":
    main()
